"""Private on-disk library. FTS stores Chinese bigrams, with page-level checkpoints."""

import hashlib
import os
from pathlib import Path
import re
import sqlite3
from contextlib import contextmanager

from .knowledge import tokens


def root():
    path = (
        Path(
            os.getenv(
                "COACHLOOP_LIBRARY_DIR",
                str(Path(__file__).resolve().parents[2] / ".local-library"),
            )
        )
        .expanduser()
        .resolve()
    )
    path.mkdir(parents=True, exist_ok=True, mode=0o700)
    (path / "pdfs").mkdir(exist_ok=True, mode=0o700)
    return path


@contextmanager
def db():
    con = sqlite3.connect(root() / "library.sqlite3", timeout=20)
    con.row_factory = sqlite3.Row
    try:
        con.execute("PRAGMA foreign_keys=ON")
        con.execute("PRAGMA secure_delete=ON")
        yield con
        con.commit()
    except Exception:
        con.rollback()
        raise
    finally:
        con.close()


def initialize():
    with db() as con:
        con.execute("PRAGMA journal_mode=WAL")
        con.executescript("""
        CREATE TABLE IF NOT EXISTS documents (
          id TEXT PRIMARY KEY, sha256 TEXT UNIQUE NOT NULL, title TEXT NOT NULL,
          author TEXT NOT NULL, edition TEXT NOT NULL, provenance TEXT NOT NULL,
          total_pages INTEGER NOT NULL, status TEXT NOT NULL DEFAULT 'queued',
          ocr INTEGER NOT NULL DEFAULT 0, cloud_allowed INTEGER NOT NULL DEFAULT 0,
          error TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
        CREATE TABLE IF NOT EXISTS pages (
          doc_id TEXT REFERENCES documents(id) ON DELETE CASCADE,
          pdf_page INTEGER NOT NULL, printed_page TEXT, chapter TEXT,
          text TEXT NOT NULL, extraction TEXT NOT NULL, quality REAL,
          text_status TEXT NOT NULL, review_status TEXT NOT NULL DEFAULT 'pending',
          error TEXT NOT NULL DEFAULT '', PRIMARY KEY(doc_id,pdf_page));
        CREATE TABLE IF NOT EXISTS chunks (
          id TEXT PRIMARY KEY, doc_id TEXT REFERENCES documents(id) ON DELETE CASCADE,
          pdf_page INTEGER NOT NULL, ordinal INTEGER NOT NULL, content TEXT NOT NULL);
        CREATE VIRTUAL TABLE IF NOT EXISTS chunks_fts USING fts5(id UNINDEXED, terms, tokenize='unicode61');
        """)
        columns = {row[1] for row in con.execute("PRAGMA table_info(pages)")}
        if "ocr_attempted" not in columns:
            con.execute(
                "ALTER TABLE pages ADD COLUMN ocr_attempted INTEGER NOT NULL DEFAULT 0"
            )
        if "chapter_source" not in columns:
            con.execute("ALTER TABLE pages ADD COLUMN chapter_source TEXT")
        # Interrupted jobs retain committed pages; resume on next application startup.
        con.execute("UPDATE documents SET status='queued' WHERE status='processing'")


def document(doc_id):
    with db() as con:
        row = con.execute("SELECT * FROM documents WHERE id=?", (doc_id,)).fetchone()
    return dict(row) if row else None


def documents():
    with db() as con:
        rows = con.execute("""SELECT d.*,
          COUNT(p.pdf_page) processed_pages,
          SUM(CASE WHEN p.text_status IN ('extracted_unchecked','checked','ocr_unchecked') AND length(p.text)>0 THEN 1 ELSE 0 END) searchable_pages,
          SUM(CASE WHEN p.extraction='ocr' THEN 1 ELSE 0 END) ocr_pages,
          SUM(CASE WHEN p.ocr_attempted=1 AND p.extraction='failed' THEN 1 ELSE 0 END) ocr_failed_pages,
          SUM(CASE WHEN p.extraction='failed' THEN 1 ELSE 0 END) failed_pages,
          SUM(CASE WHEN p.text_status IN ('low_quality','needs_ocr','needs_review') THEN 1 ELSE 0 END) review_pages,
          SUM(CASE WHEN p.text_status='low_quality' THEN 1 ELSE 0 END) low_quality_pages,
          SUM(CASE WHEN p.text_status='needs_ocr' THEN 1 ELSE 0 END) needs_ocr_pages,
          SUM(CASE WHEN p.text_status='ocr_unchecked' THEN 1 ELSE 0 END) unchecked_ocr_pages
          FROM documents d LEFT JOIN pages p ON p.doc_id=d.id GROUP BY d.id ORDER BY d.created_at,d.id""").fetchall()
    return [
        {
            **dict(row),
            "processed_pages": row["processed_pages"],
            "searchable_pages": row["searchable_pages"] or 0,
            "missing_pages": row["total_pages"] - row["processed_pages"],
        }
        for row in rows
    ]


def pdf_path(doc_id):
    # IDs are opaque, generated by the server, and validated before any file access.
    if not re.fullmatch(r"[a-f0-9]{32}", doc_id):
        raise ValueError("invalid document id")
    return root() / "pdfs" / f"{doc_id}.pdf"


def page_record(doc_id, page):
    with db() as con:
        row = con.execute(
            "SELECT * FROM pages WHERE doc_id=? AND pdf_page=?", (doc_id, page)
        ).fetchone()
    return dict(row) if row else None


def write_page(
    doc_id, result, printed_page=None, chapter=None, review_status="pending"
):
    chapter = chapter or result.get("chapter")
    chapter_source = (
        ("human_checked" if result["text_status"] == "checked" else "pdf_outline")
        if chapter
        else None
    )
    number = result["page"]
    text = result["text"]
    with db() as con:
        old = con.execute(
            "SELECT id FROM chunks WHERE doc_id=? AND pdf_page=?", (doc_id, number)
        ).fetchall()
        for row in old:
            con.execute("DELETE FROM chunks_fts WHERE id=?", (row["id"],))
        con.execute(
            "DELETE FROM chunks WHERE doc_id=? AND pdf_page=?", (doc_id, number)
        )
        con.execute(
            """INSERT OR REPLACE INTO pages
          (doc_id,pdf_page,printed_page,chapter,text,extraction,quality,text_status,review_status,error,chapter_source,ocr_attempted)
          VALUES (?,?,?,?,?,?,?,?,?,?,?,?)""",
            (
                doc_id,
                number,
                printed_page,
                chapter,
                text,
                result["extraction"],
                result["quality"],
                result["text_status"],
                review_status,
                result.get("error", ""),
                chapter_source,
                int(result.get("ocr_attempted", result["extraction"] == "ocr")),
            ),
        )
        if result["text_status"] not in (
            "extracted_unchecked",
            "checked",
            "ocr_unchecked",
        ):
            return
        # Bounded overlapping blocks; preserve PDF page boundaries.
        for ordinal, start in enumerate(range(0, len(text), 400)):
            block = text[start : start + 480].strip()
            if not block:
                continue
            digest = hashlib.sha256(block.encode()).hexdigest()[:12]
            chunk_id = f"local:{doc_id}:{number}:{ordinal}:{digest}"
            con.execute(
                "INSERT INTO chunks VALUES (?,?,?,?,?)",
                (chunk_id, doc_id, number, ordinal, block),
            )
            metadata = con.execute(
                "SELECT title,author FROM documents WHERE id=?", (doc_id,)
            ).fetchone()
            terms = " ".join(
                sorted(
                    tokens(
                        re.sub(r"(?<=[\u4e00-\u9fff])\s+(?=[\u4e00-\u9fff])", "", block)
                        + " "
                        + metadata["title"]
                        + " "
                        + metadata["author"]
                        + " "
                        + (chapter or "")
                    )
                )
            )
            con.execute("INSERT INTO chunks_fts VALUES (?,?)", (chunk_id, terms))


def search(query, limit=8, cloud_only=False, doc_id=None):
    terms = sorted(tokens(query))[:48]
    if not terms:
        return []
    expression = " OR ".join('"' + term.replace('"', '""') + '"' for term in terms)
    where = ""
    params = [expression]
    if cloud_only:
        where += " AND d.cloud_allowed=1 AND p.text_status IN ('checked','extracted_unchecked')"
    if doc_id:
        where += " AND c.doc_id=?"
        params.append(doc_id)
    params.append(min(limit * 12, 360))
    with db() as con:
        rows = con.execute(
            """SELECT c.*,d.title,d.author,d.edition,d.provenance,d.cloud_allowed,
          p.printed_page,p.chapter,p.chapter_source,p.extraction,p.quality,p.text_status,p.review_status, bm25(chunks_fts) AS rank
          FROM chunks_fts JOIN chunks c ON c.id=chunks_fts.id
          JOIN documents d ON d.id=c.doc_id JOIN pages p ON p.doc_id=c.doc_id AND p.pdf_page=c.pdf_page
          WHERE chunks_fts MATCH ?"""
            + where
            + " ORDER BY rank,c.id LIMIT ?",
            params,
        ).fetchall()
    result = []
    seen = set()
    for row in rows:
        r = dict(row)
        # One strongest block per page prevents overlapping duplicate evidence.
        identity = (r["doc_id"], r["pdf_page"])
        if identity in seen:
            continue
        seen.add(identity)
        result.append(
            {
                "id": r["id"],
                "document_id": r["doc_id"],
                "title": r["title"],
                "authors": r["author"],
                "edition": r["edition"],
                "provenance": r["provenance"],
                "chapter": r["chapter"],
                "chapter_source": r["chapter_source"],
                "pdf_page": r["pdf_page"],
                "printed_page": r["printed_page"],
                "pages": f"PDF {r['pdf_page']}"
                + (
                    f"／印刷 {r['printed_page']}"
                    if r["printed_page"]
                    else "／印刷页码未核对"
                ),
                "content": r["content"],
                "source_type": "本地PDF正文"
                if r["extraction"] == "text"
                else "本机离线OCR",
                "verification_status": r["review_status"],
                "text_status": r["text_status"],
                "ocr_quality": r["quality"],
                "cloud_allowed": bool(r["cloud_allowed"]),
                "can_send": bool(r["cloud_allowed"])
                and r["text_status"] in ("checked", "extracted_unchecked"),
                "preview_url": f"/api/library/documents/{r['doc_id']}/pages/{r['pdf_page']}/image",
                "original_url": f"/api/library/documents/{r['doc_id']}/original#page={r['pdf_page']}",
            }
        )
        if len(result) >= limit:
            break
    return result


def remove(doc_id):
    with db() as con:
        ids = con.execute("SELECT id FROM chunks WHERE doc_id=?", (doc_id,)).fetchall()
        for row in ids:
            con.execute("DELETE FROM chunks_fts WHERE id=?", (row["id"],))
        con.execute("DELETE FROM documents WHERE id=?", (doc_id,))
    pdf_path(doc_id).unlink(missing_ok=True)
    with db() as con:
        con.execute("PRAGMA wal_checkpoint(TRUNCATE)")
